"""Next-move prediction accuracy of the opponent model.

    python scripts/evaluate_opponent_model.py --games 40 --seed 5

For each opponent type, simulated games are played against a neutral partner. For every move an
opponent makes after a warm-up of observed moves, the model predicts it *before* seeing it and
is scored on top-1 / top-3 accuracy. Baselines: uniform over legal moves, and a fixed balanced
heuristic that never adapts. Opponents marked (out of library) are not generated by any style in
the model's library, which is the honest test of generalisation.
"""

from __future__ import annotations

import argparse
import asyncio
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tiles.azul.game import play_game  # noqa: E402
from tiles.azul.rules import get_legal_actions  # noqa: E402
from tiles.ml.greedy_player import (  # noqa: E402
    DEFAULT_WEIGHTS, BlockerPlayer, ColorCollectorPlayer, GreedyPlayer, RecklessPlayer, RusherPlayer,
)
from tiles.ml.minimax_player import MinimaxPlayer  # noqa: E402
from tiles.ml.opponent_model import OpponentModel, move_distribution  # noqa: E402
from tiles.ml.rollout_player import RolloutPlayer  # noqa: E402

WARMUP = 6


class Noisy:
    """Wraps a player: with probability eps it plays a random legal move (a fallible opponent)."""

    def __init__(self, inner, eps, seed):
        self.inner, self.eps, self.rng = inner, eps, random.Random(seed)
        self.name = inner.name

    async def decide(self, state, idx):
        if self.rng.random() < self.eps:
            return self.rng.choice(get_legal_actions(state, idx))
        return await self.inner.decide(state, idx)


OPPONENTS = {
    "Greedy (in library)": lambda s: GreedyPlayer(),
    "Blocker (in library)": lambda s: BlockerPlayer(),
    "Reckless (in library)": lambda s: RecklessPlayer(),
    "Rusher, 10% noise (in library)": lambda s: Noisy(RusherPlayer(), 0.10, s),
    "ColorCollector, 20% noise (in library)": lambda s: Noisy(ColorCollectorPlayer(), 0.20, s),
    "Rollout lookahead (out of library)": lambda s: RolloutPlayer(seed=s),
    "Minimax d2 (out of library)": lambda s: MinimaxPlayer(depth=2),
}


async def evaluate(make, games, seed):
    hits1 = hits3 = base1 = n = 0
    uni_exp = 0.0
    for g in range(games):
        rng = random.Random(seed * 1000 + g)
        opp = make(rng.randrange(10**6))
        partner = GreedyPlayer()
        order = [opp, partner] if g % 2 == 0 else [partner, opp]
        names = ["OPP", "PARTNER"] if g % 2 == 0 else ["PARTNER", "OPP"]
        log = []

        def hook(sim, idx, action):
            if sim.state.players[idx].name == "OPP":
                log.append((sim.state.model_copy(deep=True), idx, action))

        await play_game([p.decide for p in order], names, seed=rng.randrange(10**9), on_move=hook)
        model = OpponentModel()
        for t, (state, idx, action) in enumerate(log):
            if t >= WARMUP:
                top = model.predict(state, idx, k=3)
                n += 1
                hits1 += bool(top) and top[0][0] == action
                hits3 += any(a == action for a, _ in top)
                acts, probs = move_distribution(state, idx, DEFAULT_WEIGHTS, 1.0)
                best = acts[max(range(len(probs)), key=probs.__getitem__)]
                base1 += best == action
                uni_exp += 1 / max(1, len(acts))
            model.observe(state, idx, action)
    return {"n": n, "top1": hits1 / n, "top3": hits3 / n, "balanced_top1": base1 / n, "uniform_top1": uni_exp / n}


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--games", type=int, default=30)
    ap.add_argument("--seed", type=int, default=5)
    a = ap.parse_args()
    print(f"{'opponent':<42}{'moves':>7}{'top-1':>8}{'top-3':>8}{'fixed balanced':>16}{'uniform':>9}")
    for name, make in OPPONENTS.items():
        r = await evaluate(make, a.games, a.seed)
        print(f"{name:<42}{r['n']:>7}{r['top1']:>8.2f}{r['top3']:>8.2f}{r['balanced_top1']:>16.2f}{r['uniform_top1']:>9.3f}", flush=True)


if __name__ == "__main__":
    asyncio.run(main())
